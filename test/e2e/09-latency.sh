#!/usr/bin/env bash
# Keystroke latency (DESIGN §14) in the Docker NAT harness, one method for every row
# (test/e2e/keystroke.py run on a: type a letter into `cat` in a tmux session on b, time
# its echo). Rows: jaunt direct, jaunt relayed (UDP between a's and b's routers blocked so
# only the relay path is left), and OpenSSH from a to b with ProxyJump through the relay
# host over b's `ssh -R` tunnel (today's Cloudflare-like setup) with ObscureKeystrokeTiming
# at its default and =no. Each at harness delay 0 and 20 ms per router hop.
# Results: target/tmp/09-latency.tsv and docs/measurements.md (regenerated).
#   JAUNT_BIN=target/release/jaunt SAMPLES=200 test/e2e/09-latency.sh
set -uo pipefail
E2E_NAME=09-latency
. "$(dirname "$0")/lib.sh"

BIN=${JAUNT_BIN:-$ROOT/target/release/jaunt}
[ -x "$BIN" ] || { echo "no jaunt binary at $BIN (cargo build --release)"; exit 2; }
OUT=$ROOT/target/tmp/$E2E_NAME
SAMPLES=${SAMPLES:-200}
DELAYS=${DELAYS:-"0 20"}
DOC=${DOC:-$ROOT/docs/measurements.md}
rm -f "$OUT"-* "$OUT.tsv"

force_relay() { # on|off
  local r peer
  for r in a b; do
    peer=$([ "$r" = a ] && echo 198.51.100.12 || echo 198.51.100.11)
    docker exec "jaunt-rtr-$r" sh -c "while iptables -D FORWARD -p udp -d $peer -m comment --comment jaunt-force-relay -j DROP 2>/dev/null; do :; done"
    [ "$1" = on ] && docker exec "jaunt-rtr-$r" iptables -I FORWARD 1 -p udp -d "$peer" -m comment --comment jaunt-force-relay -j DROP
  done
  return 0
}
h_cleanup_extra() { force_relay off; }
restart() { h_daemon_restart "$1"; }

h_begin
check "mesh a b c linked and connected" h_mesh
check "a -> b DIRECT" wait_until 30 h_is_state a b direct
h_put a keystroke.py
"$H_JH" tunnel b >/dev/null 2>&1
check "baseline: b's sshd reachable on the relay host through its ssh -R tunnel" \
  h_exec a ssh -o BatchMode=yes -J relay -p 2202 jaunt@127.0.0.1 true

# measure <label> <delay> <cmd...>
measure() {
  local label=$1 delay=$2 f; shift 2
  f="$OUT-$(echo "$label-$delay" | tr ' =()' '____').json"
  h_exec a python3 /tmp/keystroke.py "$SAMPLES" -- "$@" > "$f" 2>&1
  if python3 -c 'import json,sys; d=json.load(open(sys.argv[1])); assert "median" in d and d["timeouts"]==0' "$f" 2>/dev/null; then
    local med p95
    read -r med p95 < <(python3 -c 'import json,sys; d=json.load(open(sys.argv[1])); print(d["median"], d["p95"])' "$f")
    pass "$label at ${delay} ms: median $med ms, p95 $p95 ms ($SAMPLES samples)"
    h_row "$OUT.tsv" "$delay" "$label" "$SAMPLES" "$med" "$p95" "$(basename "$f")"
  else
    fail "$label at ${delay} ms: $(head -c 300 "$f")"
  fi
}
ping_ms() { h_exec a ping -c 5 -i 0.3 -q "$1" | awk -F/ '/rtt/ {print $5}'; }

SSH_J=(ssh -tt -o BatchMode=yes -J relay -p 2202 jaunt@127.0.0.1 tmux -L lat new -A -s)
for d in $DELAYS; do
  note "harness delay $d ms per router hop (relay egress $d ms)"
  "$H_JH" delay "$d" >/dev/null 2>&1
  sleep 3
  h_row "$OUT.tsv" "$d" "ping a->relay" 5 "$(ping_ms 198.51.100.10)" "" ""
  h_row "$OUT.tsv" "$d" "ping a->b's router" 5 "$(ping_ms 198.51.100.12)" "" ""
  check "[$d ms] a -> b DIRECT" wait_until 60 h_is_state a b direct
  measure "jaunt direct" "$d" jaunt "b:lat-direct-$d"
  measure "ssh via relay host (ObscureKeystrokeTiming default)" "$d" "${SSH_J[@]}" "obscure-$d"
  measure "ssh via relay host (ObscureKeystrokeTiming=no)" "$d" "${SSH_J[@]:0:2}" -o ObscureKeystrokeTiming=no "${SSH_J[@]:2}" "plain-$d"
  force_relay on
  restart a; restart b
  check "[$d ms] a -> b RELAYED once UDP between their routers is blocked" wait_until 90 h_is_state a b relay
  measure "jaunt relayed" "$d" jaunt "b:lat-relay-$d"
  force_relay off
  restart a; restart b
done
"$H_JH" delay 0 >/dev/null 2>&1
note "results (delay, row, samples, median ms, p95 ms)"; cut -f1-5 "$OUT.tsv" | sed 's/^/    /'

python3 - "$OUT.tsv" "$DOC" "$SAMPLES" <<'EOF'
import sys, datetime, subprocess
tsv, doc, samples = sys.argv[1], sys.argv[2], sys.argv[3]
rows = [l.rstrip("\n").split("\t") for l in open(tsv) if l.strip()]
ver = subprocess.run(["git", "-C", doc.rsplit("/docs/", 1)[0], "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
out = []
w = out.append
w("# Measurements\n")
w(f"Generated by `test/e2e/09-latency.sh` on {datetime.date.today()} (repository at {ver or 'unknown'}, plus uncommitted work).")
w("It is a simulation. Read the caveats before quoting any number.\n")
w("## Keystroke round trip\n")
w("| harness delay | path | samples | median (ms) | p95 (ms) |")
w("| --- | --- | --- | --- | --- |")
for r in rows:
    if r[1].startswith("ping"):
        continue
    w(f"| {r[0]} ms | {r[1]} | {r[2]} | {r[3]} | {r[4]} |")
w("\nReference round trips measured with `ping` from a in the same runs:\n")
w("| harness delay | to | mean of 5 (ms) |")
w("| --- | --- | --- |")
for r in rows:
    if r[1].startswith("ping"):
        w(f"| {r[0]} ms | {r[1][5:]} | {r[3]} |")
w("""
## Method

* **Topology** (`test/harness`): machines a and b each sit behind their own Linux NAT
  router (port-restricted cone) on a fake internet (198.51.100.0/24); the relay host is on
  that internet. jaunt's relay is a real `iroh-relay` 1.3 with TLS and QUIC address
  discovery. Containers on one host; no real network is involved.
* **Delay**: `jh delay D` puts `netem delay D ms` on both interfaces of every router and on
  the relay's egress, so the round trips are a<->relay 3D, a<->b direct 4D and
  a->relay->b 6D (for D=20: 60, 80 and 120 ms). D=0 shows the cost of the software alone.
* **What is timed** (`test/e2e/keystroke.py`, identical for every row): the tool opens an
  interactive session from a into a tmux session on b; `cat` runs there. One letter is
  written to the local pty and the clock stops when that letter comes back (the remote pty
  echoes it, tmux redraws it). 10 warm-up samples are dropped, then """ + samples + """ samples,
  50 ms apart. Median and 95th percentile are reported.
* **jaunt direct**: `jaunt b:<session>` with the a<->b path direct (checked with `jaunt ls`).
* **jaunt relayed**: the same, after blocking UDP between a's and b's routers and
  restarting both daemons, so the only path is through the relay (checked: `relay`).
* **ssh via relay host**: `ssh -tt -J relay -p 2202 jaunt@127.0.0.1 tmux ...`: b keeps
  `ssh -N -R 2202:127.0.0.1:22 relay` open, as cloudflared keeps a tunnel open today; a
  jumps through the relay host's sshd to it. Two rows: OpenSSH's default
  `ObscureKeystrokeTiming` (on, it sends chaff every 20 ms while typing and holds real
  keystrokes to that clock) and `ObscureKeystrokeTiming=no`.

## Caveats

* The relay host stands in for Cloudflare's edge. Real numbers depend on the real distances:
  from each machine to the edge or relay, and between the machines. A direct path between two
  machines on the same LAN is far shorter than any relay; between two cities it is not
  always shorter than a well-placed edge.
* netem delay is fixed, with no jitter, loss or queueing; Wi-Fi and mobile links add all
  three. Everything runs on one host, so CPU contention adds noise at D=0.
* jaunt has no predictive local echo (mosh's trick): on a relayed path every keystroke waits
  for the relay round trip, as it does with ssh.
* tmux runs on b in every row (a repaint per keystroke), so the rows compare transports, not
  tmux against no tmux.
""")
open(doc, "w").write("\n".join(out))
EOF
check "wrote $DOC" test -s "$DOC"

finish
